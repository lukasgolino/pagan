def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def _value(value: Any) -> str:
    return f"`{json.dumps(value)}`" if value is not None else "(none)"


def settings_md() -> str:
    lines = [
        HEADER + "# `pagan.toml` settings",
        "",
        "Every setting, its default and what changes when it changes. `pagan config show` lists the current values;",
        "`pagan config set <key> <value>` edits the file safely (comments kept, the whole config validated first).",
    ]
    tables: dict[str | None, list[Any]] = {}
    for setting in SETTINGS:
        tables.setdefault(setting.table, []).append(setting)
    for table, settings in tables.items():
        lines += ["", f"## `[{table}]`" if table else "## Top level", "", "| Setting | Default | Refreshes | Meaning |", "|---|---|---|---|"]
        for s in settings:
            lines.append(f"| `{s.key}` | {_cell(_value(s.default))} | {REFRESH[s.refresh]} | {_cell(s.meaning)} |")
    return "\n".join(lines) + "\n"


def lint_rules_md() -> str:
    lines = [
        HEADER + "# Lint rules",
        "",
        "`pagan lint` (and `pagan build`, which lints first) reports every problem in a file at once, each with a rule id,",
        "file, line, a `where` path and how to fix it. Errors (E) stop a build; warnings (W) don't. Warnings can be turned",
        "off project-wide (`[lint] disable` in pagan.toml) or per asset, frame or animation (the file's `lint:`).",
        "",
        "## Errors",
        "",
        "| Rule | Meaning |",
        "|---|---|",
        *(f"| {rule} | {_cell(text)} |" for rule, text in ERROR_RULES.items()),
        "",
        "## Warnings",
        "",
        "| Rule | Meaning |",
        "|---|---|",
        *(f"| {rule} | {_cell(text)} |" for rule, text in WARNING_RULES.items()),
    ]
    return "\n".join(lines) + "\n"


def notation_md() -> str:
    lines = [
        HEADER + "# Notation: every field",
        "",
        "The fields each file accepts (anything else is an error, E001). Examples and details: the skill's",
        "[reference](../../src/pagan/skill/reference.md). Fields shared by sprites, tilesets and models mean the same",
        "in each.",
    ]
    for kind, fields in NOTATION.items():
        lines += ["", f"## {_TITLES[kind]}", "", "| Field | Meaning |", "|---|---|"]
        lines += [f"| `{name}` | {_cell(text)} |" for name, text in fields.items()]
    model_only = [f"`{f}`" for f in _OWN_FIELDS if f in ("extends", "remove", "template")]
    lines += ["", f"Models: {', '.join(model_only)} are never inherited through `extends`, nor are what the asset is",
              "and how it's reviewed (`name`, `description`, `tags`, `status`, `style_version`, `lint`)."]
    return "\n".join(lines) + "\n"


PAGES = {
    "reference/settings.md": settings_md,
    "reference/lint-rules.md": lint_rules_md,
    "reference/notation.md": notation_md,
}


def notation_drift() -> list[str]:
    """Fields a parser accepts without a docs line, or documented but not accepted."""
    problems = []
    for kind, accepted in ACCEPTED.items():
        documented = set(NOTATION[kind])
        problems += [f"{kind}: `{f}` is accepted but not documented in pagan.docs.NOTATION" for f in accepted if f not in documented]
        problems += [f"{kind}: `{f}` is documented but not accepted" for f in documented if f not in accepted]
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m pagan.docs", description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a committed page differs (write nothing)")
    parser.add_argument("--docs", type=Path, default=Path("docs"), help="docs folder (default: ./docs)")
    args = parser.parse_args(argv)
    problems = notation_drift()
    for name, page in PAGES.items():
        path = args.docs / name
        text = page()
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            problems.append(f"{path} is out of date: run `python -m pagan.docs`")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
