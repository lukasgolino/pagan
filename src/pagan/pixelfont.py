# name -> (glyph rows by character, cell size, lowercase uses uppercase)
_FONTS: dict[str, tuple[dict[str, str], tuple[int, int], bool]] = {
    "3x5": (_3X5, (3, 5), True),
    "5x7": (_5X7, (5, 7), False),
}

SIZES = tuple(_FONTS)


def _grid(rows: str) -> Grid:
    return tuple(row.replace("#", INK).replace(".", TRANSPARENT) for row in rows.split(" "))


def pixel_font(size: str) -> Asset:
    """The built-in `size` font ("3x5" or "5x7") as a font sprite: one frame per printable ASCII character."""
    if size not in _FONTS:
        raise ValueError(f"no built-in pixel font {size!r} (sizes: {', '.join(SIZES)})")
    rows, cell, upper_for_lower = _FONTS[size]
    frames: dict[str, Grid] = {}
    for char in PRINTABLE:
        source = char.upper() if upper_for_lower and char.islower() else char
        frames[f"u{ord(char):02x}"] = _grid(rows[source])
    width, height = cell
    font = Font(
        glyphs=PRINTABLE,
        cell=cell,
        baseline=height,
        line_height=height + 1,
        advance=width + 1,
        spacing=1,
        space=width + 1,
    )
    return Asset(
        kind="sprite",
        name=f"pixel_font_{size}",
        path=None,
        palette=Palette(None, {}, {}),
        size=cell,
        frames=frames,
        base_frames=dict(frames),
        frame_lines=dict.fromkeys(frames),
        derived_from={},
        font=font,
    )
